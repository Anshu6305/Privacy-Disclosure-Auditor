"""Baseline schema: the sixteen tables of the approved Phase 3 design.

Revision ID: 0001_baseline
Revises: None
Create Date: 2026-11-04
Frozen:      2026-11-05

This revision is **frozen**. Every table, column, type, constraint and index
is written out explicitly below, so running it tomorrow produces exactly the
schema it produced today, whatever the SQLAlchemy models have become in the
meantime. That is the whole point of a migration and it is what the previous
version of this file did not provide.

### Why it was changed

The first version called ``Base.metadata.create_all()``. That builds whatever
the models say *at the moment it runs*, so revision 0001 was not a fixed
historical record: a teammate migrating a fresh database after a model change
would get a different schema from one who had migrated before it, with both
databases stamped ``0001_baseline`` and no revision between them to explain the
difference. Autogenerate would also find no diff, because it compares the live
database against the same models that built it.

Freezing was safe to do because the baseline had not been applied anywhere
that matters: a read-only check on 2026-11-05 found the project database
``privacy_auditor`` empty with no ``alembic_version`` table.

### How this file was produced

Rendered from the model metadata by Alembic's own ``render_python_code``
against the PostgreSQL dialect, not written by hand and not transcribed. The
generator is kept at ``backend/migrations/freeze_baseline.py`` so the
derivation is reproducible and reviewable.

Equivalence with the models is asserted by
``tests/unit/test_migration_is_frozen.py``, which runs this revision against an
empty database and compares the result against ``Base.metadata`` table by
table. If a future model change is not accompanied by a new revision, that test
fails.

### One deliberate edit to the rendered output

Alembic renders ``func.now()`` as ``sa.text('now()')`` because it was asked to
render for PostgreSQL, and ``now()`` is not a SQLite function. The models
declare ``func.now()``, which every dialect understands, so the rendered text
was replaced with ``sa.func.now()``. This keeps the revision runnable against
SQLite, which is what lets the equivalence test check it without a server.

### Later revisions

Ordinary autogenerated ones. Run
``alembic revision --autogenerate -m "..."`` against a PostgreSQL database that
is already at this baseline.
"""

