"""Baseline schema: the sixteen tables of the approved Phase 3 design.

Revision ID: 0001_baseline
Revises: None
Create Date: 2026-11-04

This revision builds the schema from the SQLAlchemy metadata in
``app.db.models`` rather than from a hand-written list of ``op.create_table``
calls.

Why: the models carry 27 CHECK constraints, 8 unique constraints and two
functional indexes for ALG-11, plus dialect variants (JSONB on PostgreSQL,
BIGINT primary keys). Transcribing all of that into a second definition would
create two sources of truth that drift apart silently, and the drift would show
up as a constraint missing in production that the tests still pass against.
Building from the metadata means the migration and the models cannot disagree.

``create_all`` emits DDL through the live dialect, so PostgreSQL receives
BIGINT and JSONB while the test suite's SQLite receives INTEGER and JSON.

Later revisions are ordinary autogenerated ones. Run
``alembic revision --autogenerate -m "..."`` against a PostgreSQL instance that
is already at this baseline; autogenerate needs a live connection, so it cannot
be produced without one.
"""

from __future__ import annotations

from collections.abc import Sequence

from alembic import op

from app.db.models import Base

revision: str = "0001_baseline"
down_revision: str | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

#: Guard against this revision silently creating a different number of tables
#: than the approved design has.
EXPECTED_TABLE_COUNT = 16


def upgrade() -> None:
    if len(Base.metadata.tables) != EXPECTED_TABLE_COUNT:
        raise RuntimeError(
            f"Expected {EXPECTED_TABLE_COUNT} tables in the approved design, "
            f"found {len(Base.metadata.tables)}. Adding or removing a table is "
            f"a design change and needs its own migration and a requirement "
            f"change-log entry."
        )
    Base.metadata.create_all(bind=op.get_bind())


def downgrade() -> None:
    Base.metadata.drop_all(bind=op.get_bind())
